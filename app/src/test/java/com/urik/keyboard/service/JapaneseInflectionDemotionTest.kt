package com.urik.keyboard.service

import android.content.Context
import androidx.room.Room
import com.urik.keyboard.data.database.KeyboardDatabase
import com.urik.keyboard.data.database.UserKanjiFrequencyDao
import java.util.concurrent.Executor
import kotlinx.coroutines.ExperimentalCoroutinesApi
import kotlinx.coroutines.test.StandardTestDispatcher
import kotlinx.coroutines.test.TestCoroutineScheduler
import kotlinx.coroutines.test.advanceUntilIdle
import kotlinx.coroutines.test.runTest
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.RuntimeEnvironment

/**
 * The inflected-form demotion (`dictionaries/ja.demoted`, generated by
 * `tools/demote_ja_conjugations.py` and applied with [KanaKanjiConverter.INFLECTION_PENALTY]).
 *
 * Runs against the REAL bundled assets, because the whole point is the ranking those assets
 * produce: `ja_readings.txt` is flattened from Mozc, which stores every conjugated form as its own
 * entry carrying the verb's cost, so without the demotion the volitional 住もう (16606) buried
 * 相撲 (15222) and the bare サ変 fragment 住し buried 重視.
 */
@OptIn(ExperimentalCoroutinesApi::class)
@RunWith(RobolectricTestRunner::class)
class JapaneseInflectionDemotionTest {
    private val testScheduler = TestCoroutineScheduler()
    private val testDispatcher = StandardTestDispatcher(testScheduler)

    private lateinit var context: Context
    private lateinit var database: KeyboardDatabase
    private lateinit var dao: UserKanjiFrequencyDao
    private lateinit var converter: KanaKanjiConverter

    @Before
    fun setup() {
        context = RuntimeEnvironment.getApplication()
        val directExecutor = Executor { it.run() }
        database =
            Room
                .inMemoryDatabaseBuilder(context, KeyboardDatabase::class.java)
                .allowMainThreadQueries()
                .setQueryExecutor(directExecutor)
                .setTransactionExecutor(directExecutor)
                .build()
        dao = database.userKanjiFrequencyDao()
        converter = KanaKanjiConverter(context, dao, testDispatcher)
    }

    @After
    fun teardown() {
        database.close()
    }

    private suspend fun frequencyOf(reading: String, surface: String): Long? =
        converter.getCandidates(reading, "ja").firstOrNull { it.surface == surface }?.frequency

    /** The bundled pairs this test pins, read straight out of the asset. */
    private fun bundledFrequency(reading: String, surface: String): Long {
        context.assets.open("dictionaries/ja_readings.txt").bufferedReader().use { reader ->
            for (line in reader.lineSequence()) {
                val parts = line.split("\t")
                if (parts.size == 3 && parts[0] == reading && parts[1] == surface) {
                    return parts[2].toLong()
                }
            }
        }
        throw AssertionError("$reading\t$surface is not in the bundled ja_readings.txt")
    }

    private fun demotedPairs(): Set<String> =
        context.assets.open("dictionaries/ja.demoted").bufferedReader().useLines { lines ->
            lines.map { it.trim() }.filter { it.isNotEmpty() }.toHashSet()
        }

    // ---------------------------------------------------------------- the reported bug

    @Test
    fun `すもう offers 相撲 before the volitional 住もう`() = runTest(testScheduler) {
        val candidates = converter.getCandidates("すもう", "ja")
        assertEquals("相撲", candidates.first().surface)
        val sumou = candidates.indexOfFirst { it.surface == "相撲" }
        val sumou2 = candidates.indexOfFirst { it.surface == "住もう" }
        assertTrue("相撲 must outrank 住もう", sumou < sumou2)
    }

    @Test
    fun `えん offers 円 before the fragment 得ん`() = runTest(testScheduler) {
        val candidates = converter.getCandidates("えん", "ja")
        val en = candidates.indexOfFirst { it.surface == "円" }
        val en2 = candidates.indexOfFirst { it.surface == "得ん" }
        assertTrue("円 must be present", en >= 0)
        assertTrue("円 must outrank 得ん", en < en2)
    }

    @Test
    fun `ふもう offers 不毛 before the volitional 踏もう`() = runTest(testScheduler) {
        val candidates = converter.getCandidates("ふもう", "ja")
        assertEquals("不毛", candidates.first().surface)
    }

    // ---------------------------------------------------------------- the penalty itself

    @Test
    fun `a demoted form loses exactly the inflection penalty`() = runTest(testScheduler) {
        val bundled = bundledFrequency("すもう", "住もう")
        assertEquals(bundled - 2_000L, frequencyOf("すもう", "住もう"))
    }

    @Test
    fun `an undemoted noun keeps its bundled frequency untouched`() = runTest(testScheduler) {
        assertEquals(bundledFrequency("すもう", "相撲"), frequencyOf("すもう", "相撲"))
        assertEquals(bundledFrequency("じゅうし", "重視"), frequencyOf("じゅうし", "重視"))
    }

    @Test
    fun `relative order among demoted forms is preserved`() = runTest(testScheduler) {
        // Both candidates for よもう are volitionals, so the demotion must not reshuffle them.
        val candidates = converter.getCandidates("よもう", "ja").map { it.surface }
        assertTrue("読もう must still precede 詠もう",
            candidates.indexOf("読もう") < candidates.indexOf("詠もう"))
    }

    // ---------------------------------------------------------------- what must NOT be demoted

    @Test
    fun `dictionary forms are never demoted`() = runTest(testScheduler) {
        for ((reading, surface) in listOf(
            "よむ" to "読む", "たべる" to "食べる", "しろい" to "白い",
            "くらい" to "暗い", "ほしい" to "欲しい", "じゅうする" to "住する"
        )) {
            assertEquals(
                "$surface is a dictionary form and must keep its rank",
                bundledFrequency(reading, surface),
                frequencyOf(reading, surface)
            )
        }
    }

    @Test
    fun `nominalisable 連用形 are never demoted`() = runTest(testScheduler) {
        // 読み, 残し, 話し are productively nouns; only a サ変 verb's 〜し (住し) is a bare fragment.
        for ((reading, surface) in listOf("よみ" to "読み", "のこし" to "残し", "はなし" to "話し")) {
            assertEquals(
                "$surface is productively a noun and must keep its rank",
                bundledFrequency(reading, surface),
                frequencyOf(reading, surface)
            )
        }
        assertEquals(
            "住し is a bare サ変 fragment, not a noun",
            bundledFrequency("じゅうし", "住し") - 2_000L,
            frequencyOf("じゅうし", "住し")
        )
    }

    // ---------------------------------------------------------------- the curated lists

    @Test
    fun `curated keep entries are honoured`() = runTest(testScheduler) {
        // tools/demoted_manual/ja.keep — lexicalised (向こう) and far-commoner-than-the-rival (良く).
        for ((reading, surface) in listOf("むこう" to "向こう", "よく" to "良く", "たいし" to "対し")) {
            assertEquals(
                "$surface is on ja.keep and must keep its rank",
                bundledFrequency(reading, surface),
                frequencyOf(reading, surface)
            )
        }
    }

    @Test
    fun `curated demote entries are honoured`() = runTest(testScheduler) {
        // tools/demoted_manual/ja.demote — Mozc reading errors the heuristic cannot reach.
        for ((reading, surface) in listOf("こうそう" to "高そう", "こよう" to "来よう")) {
            assertEquals(
                "$surface is on ja.demote and must be penalised",
                bundledFrequency(reading, surface) - 2_000L,
                frequencyOf(reading, surface)
            )
        }
    }

    @Test
    fun `こうそう offers 構想 before the misfiled 高そう`() = runTest(testScheduler) {
        val candidates = converter.getCandidates("こうそう", "ja").map { it.surface }
        assertTrue("構想 must outrank 高そう",
            candidates.indexOf("構想") < candidates.indexOf("高そう"))
    }

    // ---------------------------------------------------------------- the asset

    @Test
    fun `the demotion asset is well formed`() {
        val lines = context.assets.open("dictionaries/ja.demoted").bufferedReader().readLines()
        assertTrue("the asset must not be empty", lines.size > 10_000)
        for (line in lines) {
            val parts = line.split("\t")
            assertEquals("every line is reading<TAB>surface: $line", 2, parts.size)
            assertTrue("neither field may be blank: $line",
                parts[0].isNotBlank() && parts[1].isNotBlank())
        }
    }

    @Test
    fun `no curated keep entry survives in the generated asset`() {
        val demoted = demotedPairs()
        for (pair in listOf(
            "むこう\t向こう", "よく\t良く", "たいし\t対し", "まとう\t待とう",
            "いえよう\t言えよう", "うえん\t植えん", "なめん\t舐めん"
        )) {
            assertFalse("$pair is on ja.keep and must not be in ja.demoted", pair in demoted)
        }
    }

    // ---------------------------------------------------------------- interaction with learning

    @Test
    fun `registration still overrides a demoted form`() = runTest(testScheduler) {
        converter.registerEntry("すもう", "角力")
        advanceUntilIdle()
        val candidates = converter.getCandidates("すもう", "ja")
        assertEquals("a registered surface leads regardless of demotion", "角力",
            candidates.first().surface)
        assertNotNull(candidates.firstOrNull { it.surface == "相撲" })
    }

    @Test
    fun `selecting a demoted form still learns it`() = runTest(testScheduler) {
        val before = frequencyOf("すもう", "住もう")!!
        converter.recordSelection("すもう", "住もう")
        advanceUntilIdle()
        val after = frequencyOf("すもう", "住もう")!!
        assertTrue("a learned selection must climb from the demoted base", after > before)
    }
}
